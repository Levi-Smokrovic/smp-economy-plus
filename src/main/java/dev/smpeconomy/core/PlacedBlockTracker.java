/**
 * Tracks blocks placed by real players (not FakePlayers) or generated by fluids (cobble, stone, basalt and obsidian
 * generators), so jobs and tasks do not pay for placed blocks. Stored in {@code placed_blocks.dat}: GZIP, per dimension
 * a set of {@code BlockPos.asLong()}.
 *
 * <p>Rules, see the mixins in {@code core.mixin}: marks after a successful {@code BlockItem.placeBlock} by a real
 * ServerPlayer, including saplings and crops, so farmer logic must check crop age rather than this. Unmarks only when
 * air or a fluid appears at the position; state changes (growth, stripping, oxidation, dirt to grass) keep the mark.
 * Removal is deferred to tick end, so {@link #isPlayerPlaced} still returns true in the tick of breaking and is safe in
 * {@code PlayerBlockBreakEvents.AFTER}. Falling blocks carry the mark as an entity tag, and pistons move it. Not
 * covered: endermen, dragon egg teleports. A crash loses at most changes since the last save (60 s or less).
 *
 * <p>Fail-closed: if the file is unreadable at startup, or missing despite traces ({@code .corrupt-*}, {@code .tmp}, a
 * copy in a restore point, or an existing {@code players.json}), {@link #reliable()} is false. {@link #isPlayerPlaced}
 * then reports every block as placed so breaking pays nothing, nothing is saved so the traces stay, and admins see the
 * problem ({@link #problem()}, {@code /smpeco status}). Admins either run {@code /smpeco placed confirm} (
 * {@link #acknowledge}) to continue without the old marks, or put back the copy from the newest restore point and restart.
 *
 * <p>Server thread only; calls from other threads are ignored. The exception is saving: the server thread copies the
 * sets, then compression and writing run on an IO thread (one write at a time, {@link #save()} waits) so a large file
 * does not stall a tick.
 */
public final class PlacedBlockTracker {
	public static final String FALLING_TAG = "smpeco_placed";
	public static final String FILE = "placed_blocks.dat";
	private static final int MAGIC = 0x54524250;
	private static final int VERSION = 1;
	private static final long SAVE_INTERVAL_MS = 60_000;
	/** The file grows with building activity. */
	private static final long SLOW_WRITE_MS = 1_000;
	private static final long SYNC_WAIT_SECONDS = 120;

	private static final Store LIVE = new Store();
	private static Thread serverThread;
	private static boolean dirty;
	/** Without a successful load nothing is saved, or an empty set would overwrite the file. */
	private static boolean loaded;
	/** False means fail-closed, see the class doc. */
	private static boolean reliable;
	private static String problem;
	private static long lastSave;
	/** One FIFO thread: writes never overtake each other, sync saves wait behind a running one. */
	private static ExecutorService io;
	private static Future<?> pendingWrite;
	/** Set by the IO thread when a write fails; the server thread then marks dirty again. */
	private static volatile boolean writeFailed;

	private PlacedBlockTracker() {}

	/** True in the tick of breaking. While unreliable, every block counts as placed so breaking pays nothing. */
	public static boolean isPlayerPlaced(Level level, BlockPos pos) {
		return !reliable || LIVE.contains(key(level), pos.asLong());
	}

	public static boolean reliable() {
		return reliable;
	}

	public static java.util.Optional<String> problem() {
		return reliable ? java.util.Optional.empty() : java.util.Optional.of(problem != null ? problem : FILE + " not loaded");
	}

	public static void markPlaced(Level level, BlockPos pos) {
		if (!onServerThread()) return;
		if (LIVE.add(key(level), pos.asLong())) dirty = true;
	}

	public static void unmark(Level level, BlockPos pos) {
		if (!onServerThread()) return;
		if (LIVE.remove(key(level), pos.asLong())) dirty = true;
	}

	public static int size() {
		return LIVE.size();
	}

	public static int countMatching(Level level, java.util.function.LongPredicate filter) {
		LongOpenHashSet set = LIVE.placed.get(key(level));
		if (set == null) return 0;
		int n = 0;
		for (LongIterator it = set.iterator(); it.hasNext(); ) if (filter.test(it.nextLong())) n++;
		return n;
	}

	public static List<BlockPos> placedMatching(Level level, java.util.function.LongPredicate filter, int limit) {
		List<BlockPos> out = new ArrayList<>();
		LongOpenHashSet set = LIVE.placed.get(key(level));
		if (set == null) return out;
		for (LongIterator it = set.iterator(); it.hasNext() && out.size() < limit; ) {
			long p = it.nextLong();
			if (filter.test(p)) out.add(BlockPos.of(p));
		}
		return out;
	}

	public static void onFluidGenerated(Level level, BlockPos pos) {
		if (!(level instanceof ServerLevel) || !onServerThread()) return;
		if (LIVE.add(key(level), pos.asLong())) dirty = true;
	}

	/** Hot path: cheap checks first. */
	public static void onBlockChanged(Level level, BlockPos pos, BlockState newState) {
		if (LIVE.isEmpty() || !(newState.isAir() || newState.getBlock() instanceof LiquidBlock)) return;
		if (!(level instanceof ServerLevel) || !onServerThread()) return;
		LIVE.scheduleRemoval(key(level), pos.asLong());
	}

	public static List<BlockPos> placedAmong(Level level, List<BlockPos> positions) {
		if (LIVE.isEmpty() || positions.isEmpty()) return List.of();
		List<BlockPos> result = new ArrayList<>();
		String dim = key(level);
		for (BlockPos p : positions) {
			if (LIVE.contains(dim, p.asLong())) result.add(p.immutable());
		}
		return result;
	}

	public static void onPistonMoved(Level level, List<BlockPos> moved, Direction dir) {
		if (!onServerThread()) return;
		String dim = key(level);
		for (BlockPos p : moved) LIVE.remove(dim, p.asLong());
		for (BlockPos p : moved) LIVE.add(dim, p.relative(dir).asLong());
		dirty = true;
	}

	public static void endTick() {
		if (LIVE.applyRemovals()) dirty = true;
	}

	/**
	 * A missing file with no traces (new world) gets an empty file written immediately, so it is in the restore point
	 * from the next start on. Broken or missing despite traces fails closed, see the class doc.
	 */
	public static void load(net.minecraft.server.MinecraftServer server) {
		serverThread = Thread.currentThread();
		LIVE.clear();
		loaded = false;
		reliable = false;
		problem = null;
		lastSave = System.currentTimeMillis();
		Path file = DataStore.dataDir().resolve(FILE);
		List<String> traces = new ArrayList<>(DataStore.restorePointsContaining(FILE));
		if (DataStore.presentAtStart().contains("players.json")) traces.add("players.json present");
		Inspection r = inspect(file, traces);
		problem = r.problem();
		if (r.store() == null) {
			// File broken and could not be moved aside: never save, or an empty set overwrites the file.
			SmpEconomy.LOG.error("[SMPEco] {}: breaking pays nothing until the file is repaired (check {}, then restart)", problem, file);
			return;
		}
		LIVE.copyFrom(r.store());
		loaded = true;
		reliable = r.reliable();
		dirty = false;
		if (!reliable) {
			List<String> copies = DataStore.restorePointsContaining(FILE);
			SmpEconomy.LOG.error("[SMPEco] ===== {}: {}. Jobs, tasks and missions pay NOTHING for breaking until an admin decides =====", FILE, problem);
			SmpEconomy.LOG.error("[SMPEco]  (a) Put a copy back: copy {} to {} and restart (blocks placed since then count as natural)",
				copies.isEmpty() ? "(no restore point with a copy)" : DataStore.backupRoot().resolve(copies.get(0)).resolve(FILE), file);
			SmpEconomy.LOG.error("[SMPEco]  (b) /smpeco placed confirm: continue without the old marks (ALL blocks placed so far count as natural)");
			return;
		}
		if (r.fresh()) {
			dirty = true;
			save(); // empty file: in the restore point from next start on, so absence is detected
		}
		SmpEconomy.LOG.info("[SMPEco] {} placed blocks loaded", LIVE.size());
	}

	/** Used to avoid storing a broken copy in a restore point. */
	public static boolean isReadable(Path file) {
		if (!Files.isRegularFile(file)) return false;
		try (InputStream in = Files.newInputStream(file)) {
			new Store().readFrom(in);
			return true;
		} catch (IOException | RuntimeException e) {
			return false;
		}
	}

	public record Inspection(Store store, boolean reliable, boolean fresh, String problem) {}

	/**
	 * Reads {@code file} into a new set without touching the live tracker. Public for selftests. A broken file moves to
	 * {@code <file>.corrupt-<time>} and yields an empty, unreliable set (store is null if the move fails). A missing
	 * file is new and reliable unless there are traces: {@code .corrupt-*} or {@code .tmp} next to it, or
	 * {@code extraTraces}.
	 */
	public static Inspection inspect(Path file, List<String> extraTraces) {
		Store store = new Store();
		if (Files.exists(file)) {
			try (InputStream in = Files.newInputStream(file)) {
				store.readFrom(in);
				return new Inspection(store, true, false, null);
			} catch (IOException | RuntimeException e) {
				Path aside = file.resolveSibling(file.getFileName() + ".corrupt-" + System.currentTimeMillis());
				SmpEconomy.LOG.error("[SMPEco] {} not readable, moving to {}", file, aside, e);
				try {
					Files.move(file, aside);
				} catch (IOException moveError) {
					SmpEconomy.LOG.error("[SMPEco] Could not move {}", file, moveError);
					return new Inspection(null, false, false, file.getFileName() + " unreadable and can't be moved (" + e + ")");
				}
				return new Inspection(new Store(), false, false, file.getFileName() + " was unreadable (" + e.getMessage() + "), now kept as "
					+ aside.getFileName());
			}
		}
		List<String> traces = new ArrayList<>(extraTraces);
		String name = file.getFileName().toString();
		try (java.util.stream.Stream<Path> list = Files.list(file.getParent())) {
			list.map(p -> p.getFileName().toString())
				.filter(n -> n.startsWith(name + ".corrupt-") || n.equals(name + ".tmp"))
				.sorted()
				.forEach(traces::add);
		} catch (IOException | RuntimeException e) {
			traces.add("data folder unreadable (" + e + ")");
		}
		if (traces.isEmpty()) return new Inspection(store, true, true, null);
		return new Inspection(store, false, false, name + " is missing although there are traces of it (" + String.join(", ", traces) + ")");
	}

	/**
	 * {@code /smpeco placed confirm}: the admin accepts losing the old marks. From now on
	 * only blocks placed since startup count as placed, older ones as natural. Writes immediately.
	 *
	 * @return null when done, otherwise an error text
	 */
	public static String acknowledge(String who) {
		if (reliable) return "Nothing to confirm – the markers are complete.";
		if (DataStore.dataDir() == null) return "The server hasn't started yet.";
		Path file = DataStore.dataDir().resolve(FILE);
		if (!loaded) {
			// Broken file could not be moved at startup: retry, otherwise never overwrite.
			Path aside = file.resolveSibling(FILE + ".corrupt-" + System.currentTimeMillis());
			try {
				if (Files.exists(file)) Files.move(file, aside);
			} catch (IOException e) {
				return FILE + " can't be moved (" + e + ") – remove/repair the file by hand and restart.";
			}
			loaded = true;
		}
		SmpEconomy.LOG.warn("[SMPEco-admin] {}: {} confirmed ({}), {} blocks marked since startup stay, older ones count as natural",
			who, FILE, problem, LIVE.size());
		reliable = true;
		problem = null;
		dirty = true;
		save();
		return null;
	}

	public static void save() {
		Future<?> f = startWrite();
		if (f == null) return;
		try {
			f.get(SYNC_WAIT_SECONDS, TimeUnit.SECONDS);
		} catch (InterruptedException e) {
			Thread.currentThread().interrupt();
			SmpEconomy.LOG.error("[SMPEco] Waiting for {} interrupted", FILE);
		} catch (ExecutionException | TimeoutException e) {
			SmpEconomy.LOG.error("[SMPEco] Saving {} did not complete", FILE, e);
		}
		collectFailure();
	}

	public static void saveIfDirty() {
		collectFailure();
		if (dirty) save();
	}

	/** At most every 60 s, only with changes and no write running, in the background. */
	public static void saveIfDue() {
		collectFailure();
		if (!dirty || System.currentTimeMillis() - lastSave < SAVE_INTERVAL_MS) return;
		if (pendingWrite != null && !pendingWrite.isDone()) return; // next tick
		startWrite();
	}

	public static void reset() {
		Future<?> f = pendingWrite;
		if (f != null && !f.isDone()) {
			try {
				f.get(SYNC_WAIT_SECONDS, TimeUnit.SECONDS);
			} catch (InterruptedException e) {
				Thread.currentThread().interrupt();
			} catch (ExecutionException | TimeoutException e) {
				SmpEconomy.LOG.error("[SMPEco] Last save of {} did not complete", FILE, e);
			}
		}
		pendingWrite = null;
		LIVE.clear();
		serverThread = null;
		dirty = false;
		loaded = false;
		reliable = false;
		problem = null;
		writeFailed = false;
	}

	private static void collectFailure() {
		if (writeFailed) {
			writeFailed = false;
			dirty = true;
		}
	}

	/**
	 * Copies the sets on the server thread, excluding deferred removals, and hands compression and writing to the IO
	 * thread. Null if not loaded.
	 */
	private static Future<?> startWrite() {
		if (!loaded || !reliable || DataStore.dataDir() == null) return null; // unreliable: do not overwrite the traces
		Path file = DataStore.dataDir().resolve(FILE);
		Map<String, long[]> snapshot = LIVE.snapshot();
		int count = LIVE.size();
		dirty = false;
		lastSave = System.currentTimeMillis();
		if (io == null) {
			io = Executors.newSingleThreadExecutor(r -> {
				Thread t = new Thread(r, "smpeco-placed-blocks-io");
				t.setDaemon(true);
				return t;
			});
		}
		pendingWrite = io.submit(() -> {
			long start = System.nanoTime();
			try {
				DataStore.writeAtomic(file, encode(snapshot));
			} catch (IOException | RuntimeException e) {
				writeFailed = true;
				SmpEconomy.LOG.error("[SMPEco] Saving {} failed", FILE, e);
				return;
			}
			long ms = (System.nanoTime() - start) / 1_000_000;
			if (ms >= SLOW_WRITE_MS) SmpEconomy.LOG.warn("[SMPEco] {} with {} marks written in {} ms (grows over time)", FILE, count, ms);
		});
		return pendingWrite;
	}

	/** MAGIC, VERSION, dimension count, then for each (UTF id, count, longs); GZIP at BEST_SPEED. */
	static byte[] encode(Map<String, long[]> dims) throws IOException {
		ByteArrayOutputStream bytes = new ByteArrayOutputStream();
		try (DataOutputStream out = new DataOutputStream(new BufferedOutputStream(fastGzip(bytes), 1 << 16))) {
			out.writeInt(MAGIC);
			out.writeInt(VERSION);
			out.writeInt(dims.size());
			for (Map.Entry<String, long[]> e : dims.entrySet()) {
				out.writeUTF(e.getKey());
				out.writeInt(e.getValue().length);
				for (long p : e.getValue()) out.writeLong(p);
			}
		}
		return bytes.toByteArray();
	}

	private static OutputStream fastGzip(OutputStream target) throws IOException {
		return new GZIPOutputStream(target, 1 << 16) {
			{
				def.setLevel(Deflater.BEST_SPEED);
			}
		};
	}

	private static boolean onServerThread() {
		return serverThread == null || Thread.currentThread() == serverThread;
	}

	private static String key(Level level) {
		return level.dimension().identifier().toString();
	}

	public static final class Store {
		private final Map<String, LongOpenHashSet> placed = new HashMap<>();
		private final Map<String, LongOpenHashSet> pendingRemoval = new HashMap<>();
		private int size;

		public boolean contains(String dim, long pos) {
			LongOpenHashSet set = placed.get(dim);
			return set != null && set.contains(pos);
		}

		public boolean add(String dim, long pos) {
			LongOpenHashSet pending = pendingRemoval.get(dim);
			if (pending != null) pending.remove(pos);
			boolean added = placed.computeIfAbsent(dim, k -> new LongOpenHashSet()).add(pos);
			if (added) size++;
			return added;
		}

		public boolean remove(String dim, long pos) {
			LongOpenHashSet pending = pendingRemoval.get(dim);
			if (pending != null) pending.remove(pos);
			LongOpenHashSet set = placed.get(dim);
			boolean removed = set != null && set.remove(pos);
			if (removed) size--;
			return removed;
		}

		public void scheduleRemoval(String dim, long pos) {
			if (contains(dim, pos)) pendingRemoval.computeIfAbsent(dim, k -> new LongOpenHashSet()).add(pos);
		}

		public boolean applyRemovals() {
			if (pendingRemoval.isEmpty()) return false;
			boolean changed = false;
			for (Map.Entry<String, LongOpenHashSet> e : pendingRemoval.entrySet()) {
				LongOpenHashSet set = placed.get(e.getKey());
				if (set == null) continue;
				LongIterator it = e.getValue().iterator();
				while (it.hasNext()) {
					if (set.remove(it.nextLong())) {
						size--;
						changed = true;
					}
				}
			}
			pendingRemoval.clear();
			return changed;
		}

		public boolean isEmpty() {
			return size == 0;
		}

		public int size() {
			return size;
		}

		public void clear() {
			placed.clear();
			pendingRemoval.clear();
			size = 0;
		}

		public void copyFrom(Store other) {
			clear();
			for (Map.Entry<String, LongOpenHashSet> e : other.placed.entrySet()) {
				placed.put(e.getKey(), new LongOpenHashSet(e.getValue()));
				size += e.getValue().size();
			}
		}

		public byte[] toBytes() throws IOException {
			return encode(snapshot());
		}

		public Map<String, long[]> snapshot() {
			Map<String, long[]> out = new LinkedHashMap<>();
			for (Map.Entry<String, LongOpenHashSet> e : placed.entrySet()) {
				LongOpenHashSet set = e.getValue();
				LongOpenHashSet pending = pendingRemoval.get(e.getKey());
				if (pending == null || pending.isEmpty()) {
					out.put(e.getKey(), set.toLongArray());
					continue;
				}
				long[] copy = new long[set.size() - countIn(set, pending)];
				int i = 0;
				LongIterator it = set.iterator();
				while (it.hasNext()) {
					long p = it.nextLong();
					if (!pending.contains(p)) copy[i++] = p;
				}
				out.put(e.getKey(), copy);
			}
			return out;
		}

		public void readFrom(InputStream raw) throws IOException {
			clear();
			try (DataInputStream in = new DataInputStream(new BufferedInputStream(new GZIPInputStream(raw)))) {
				if (in.readInt() != MAGIC) throw new IOException("Wrong file format");
				int version = in.readInt();
				if (version != VERSION) throw new IOException("Unknown version " + version);
				int dims = in.readInt();
				for (int d = 0; d < dims; d++) {
					String dim = in.readUTF();
					int count = in.readInt();
					if (count < 0) throw new IOException("Negative count");
					LongOpenHashSet set = new LongOpenHashSet(count);
					for (int i = 0; i < count; i++) set.add(in.readLong());
					placed.put(dim, set);
					size += set.size();
				}
			}
		}

		private static int countIn(LongOpenHashSet set, LongOpenHashSet pending) {
			int n = 0;
			LongIterator it = pending.iterator();
			while (it.hasNext()) {
				if (set.contains(it.nextLong())) n++;
			}
			return n;
		}
	}
}
